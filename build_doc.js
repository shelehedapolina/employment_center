// Get image dimensions by reading PNG header
function getPngSize(filepath) {
  const buf = fs.readFileSync(filepath);
  if (buf[0] === 0x89 && buf[1] === 0x50) {
    return { width: buf.readUInt32BE(16), height: buf.readUInt32BE(20) };
  }
  return { width: 1000, height: 600 };
}

function img(filename, width = 600, dir = SCREENSHOTS) {
  let filepath = path.join(dir, filename);
  if (!fs.existsSync(filepath)) {
    // Fallback search
    const dirs = [SCREENSHOTS, SQL_SCREENSHOTS, RESIZED];
    for (const d of dirs) {
      const f = path.join(d, filename);
      if (fs.existsSync(f)) { filepath = f; break; }
    }
  }
  if (!fs.existsSync(filepath)) {
    return p(`[Зображення ${filename} не знайдено]`);
  }
  const image = fs.readFileSync(filepath);
  const dim = getPngSize(filepath);
  const height = Math.round(width * dim.height / dim.width);

  return new Paragraph({
    alignment: AlignmentType.CENTER,
    spacing: { before: 120, after: 60 },
    children: [new ImageRun({
      data: image,
      transformation: { width, height },
      type: 'png'
    })]
  });
}

function imgCaption(text) {
  return new Paragraph({
    alignment: AlignmentType.CENTER,
    spacing: { before: 60, after: 240 },
    children: [new TextRun({ text, font: FONT, size: SIZE_NORMAL, italics: true })]
  });
}

function code(text) {
  const lines = text.split('\n');
  return lines.map(line => new Paragraph({
    spacing: { line: 240, before: 0, after: 0 },
    indent: { left: 360 },
    children: [new TextRun({ text: line || ' ', font: 'Courier New', size: 20 })]
  }));
}

function bullet(text) {
  return new Paragraph({
    spacing: { line: 360, before: 0, after: 60 },
    alignment: AlignmentType.JUSTIFIED,
    indent: { left: 720, hanging: 360 },
    numbering: { reference: 'bullets', level: 0 },
    children: [new TextRun({ text, font: FONT, size: SIZE_NORMAL })]
  });
}

