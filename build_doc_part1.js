function p(text, opts = {}) {
  return new Paragraph({
    spacing: { line: 360, before: opts.before || 0, after: opts.after || 0 },
    indent: opts.firstLine !== false ? { firstLine: 720 } : undefined,
    alignment: opts.align || AlignmentType.JUSTIFIED,
    children: [new TextRun({
      text: text,
      font: FONT,
      size: SIZE_NORMAL,
      bold: opts.bold,
      italics: opts.italics
    })]
  });
}

function pCenter(text, opts = {}) {
  return new Paragraph({
    spacing: { line: 360, before: opts.before || 0, after: opts.after || 0 },
    alignment: AlignmentType.CENTER,
    children: [new TextRun({
      text: text,
      font: FONT,
      size: opts.size || SIZE_NORMAL,
      bold: opts.bold !== false,
      italics: opts.italics
    })]
  });
}

function h1(text) {
  return new Paragraph({
    heading: HeadingLevel.HEADING_1,
    spacing: { before: 240, after: 240 },
    alignment: AlignmentType.CENTER,
    pageBreakBefore: true,
    children: [new TextRun({ text: text, font: FONT, size: SIZE_H1, bold: true })]
  });
}

function h2(text) {
  return new Paragraph({
    heading: HeadingLevel.HEADING_2,
    spacing: { before: 240, after: 120 },
    children: [new TextRun({ text: text, font: FONT, size: SIZE_H2, bold: true })]
  });
}

function h3(text) {
  return new Paragraph({
    heading: HeadingLevel.HEADING_3,
    spacing: { before: 180, after: 120 },
    indent: { firstLine: 720 },
    children: [new TextRun({ text: text, font: FONT, size: SIZE_NORMAL, bold: true })]
  });
}

function img(filename, width = 600) {
  const filepath = path.join(SCREENSHOTS, filename);
  if (!fs.existsSync(filepath)) {
    return p(`[Зображення ${filename} не знайдено]`);
  }
  const image = fs.readFileSync(filepath);
  // Get original dimensions to preserve aspect ratio
  const dimensions = require('image-size')?.imageSize?.(image) || null;
  let height;
  if (dimensions) {
    height = Math.round(width * dimensions.height / dimensions.width);
  } else {
    height = Math.round(width * 0.65);
  }

  return new Paragraph({
    alignment: AlignmentType.CENTER,
    spacing: { before: 120, after: 60 },
    children: [new ImageRun({
      data: image,
      transformation: { width, height },
      type: 'png'
    })]
  });
}

function imgCaption(text) {
  return new Paragraph({
    alignment: AlignmentType.CENTER,
    spacing: { before: 60, after: 240 },
    children: [new TextRun({
      text: text, font: FONT, size: SIZE_NORMAL, italics: true
    })]
  });
}

function code(text) {
  // Render code as monospaced paragraph(s)
  const lines = text.split('\n');
  return lines.map(line => new Paragraph({
    spacing: { line: 280, before: 0, after: 0 },
    indent: { left: 360 },
    children: [new TextRun({ text: line || ' ', font: 'Courier New', size: 22 })]
  }));
}

function bullet(text) {
  return new Paragraph({
    spacing: { line: 360, before: 0, after: 60 },
    alignment: AlignmentType.JUSTIFIED,
    indent: { left: 720, hanging: 360 },
    numbering: { reference: 'bullets', level: 0 },
    children: [new TextRun({ text: text, font: FONT, size: SIZE_NORMAL })]
  });
}

